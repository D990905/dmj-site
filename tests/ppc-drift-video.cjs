const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const read = f => fs.readFileSync(path.join(__dirname, '..', f), 'utf8');
const html = read('index.html'), script = read('assets/js/drift-video.js'), css = read('assets/css/drift-video.css');
assert.equal((html.match(/id="drift-film"/g) || []).length, 1);
assert(html.indexOf('id="drift-film"') < html.indexOf('id="outlet-home"'));
assert(html.includes('https://www.youtube.com/watch?v=89btxH-v94k'));
assert(html.includes('ppc.html#supersonic'));
assert(!html.includes('<iframe'));
assert(css.includes('aspect-ratio:16/9'));
assert(css.includes('grid-template-columns:minmax(0,1fr)'));
let click, once, replacements = 0, focused = false, frame;
const player = {dataset: {}, querySelector: () => ({addEventListener: (event, fn, opts) => {assert.equal(event, 'click'); click = fn; once = opts.once;}}), replaceChildren: f => {frame = f; replacements++;}};
vm.runInNewContext(script, {document: {querySelectorAll: () => [player], createElement: tag => {assert.equal(tag, 'iframe'); return {focus: () => {focused = true;}};}}});
assert.equal(replacements, 0, 'No iframe or external request before a click');
assert(once);
click(); click();
assert.equal(replacements, 1, 'Repeated clicks create only one iframe');
assert.equal(frame.src, 'https://www.youtube-nocookie.com/embed/89btxH-v94k?autoplay=1&controls=1&playsinline=1&rel=0');
assert.equal(frame.referrerPolicy, 'strict-origin-when-cross-origin');
assert(frame.title.includes('Drift'));
assert(frame.allowFullscreen && focused);
console.log('PASS: exact official video, preserved content, local poster, click-only privacy embed, one iframe, controls, referrer policy, keyboard focus and responsive CSS contract.');
